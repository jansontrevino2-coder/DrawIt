-- Fresh DrawIt setup. Run once in the Supabase SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (char_length(username) between 3 and 30),
  avatar_url text,
  updated_at timestamptz default now()
);
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 500),
  created_at timestamptz not null default now()
);
create table if not exists public.replies (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  type text not null check (type in ('text','drawing')),
  content text not null,
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.replies enable row level security;

drop policy if exists "profiles readable" on public.profiles;
drop policy if exists "insert own profile" on public.profiles;
drop policy if exists "update own profile" on public.profiles;
create policy "profiles readable" on public.profiles for select to authenticated using (true);
create policy "insert own profile" on public.profiles for insert to authenticated with check ((select auth.uid())=id);
create policy "update own profile" on public.profiles for update to authenticated using ((select auth.uid())=id) with check ((select auth.uid())=id);

drop policy if exists "posts readable" on public.posts;
drop policy if exists "create own posts" on public.posts;
drop policy if exists "delete own posts" on public.posts;
create policy "posts readable" on public.posts for select to authenticated using (true);
create policy "create own posts" on public.posts for insert to authenticated with check ((select auth.uid())=user_id);
create policy "delete own posts" on public.posts for delete to authenticated using ((select auth.uid())=user_id);

drop policy if exists "replies readable" on public.replies;
drop policy if exists "create own replies" on public.replies;
drop policy if exists "delete own replies" on public.replies;
create policy "replies readable" on public.replies for select to authenticated using (true);
create policy "create own replies" on public.replies for insert to authenticated with check ((select auth.uid())=user_id);
create policy "delete own replies" on public.replies for delete to authenticated using ((select auth.uid())=user_id);

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('avatars','avatars',true,2097152,array['image/png','image/jpeg','image/webp','image/gif'])
on conflict (id) do update set public=true,file_size_limit=2097152,allowed_mime_types=array['image/png','image/jpeg','image/webp','image/gif'];

drop policy if exists "public avatar reads" on storage.objects;
drop policy if exists "upload own avatars" on storage.objects;
drop policy if exists "update own avatars" on storage.objects;
drop policy if exists "delete own avatars" on storage.objects;
create policy "public avatar reads" on storage.objects for select using (bucket_id='avatars');
create policy "upload own avatars" on storage.objects for insert to authenticated with check (bucket_id='avatars' and (storage.foldername(name))[1]=(select auth.uid()::text));
create policy "update own avatars" on storage.objects for update to authenticated using (bucket_id='avatars' and owner_id=(select auth.uid()::text)) with check (bucket_id='avatars' and owner_id=(select auth.uid()::text));
create policy "delete own avatars" on storage.objects for delete to authenticated using (bucket_id='avatars' and owner_id=(select auth.uid()::text));
